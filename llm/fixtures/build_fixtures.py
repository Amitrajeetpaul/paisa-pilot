"""Builds llm/fixtures/*.json -- full schema-envelope reader output for the
4 flagship sample_data documents, derived from sample_data/ground_truth/*.json.

These stand in for "what Gemini 3.8 Flash actually returned" for our own
clean, synthetic PDFs (generated by sample_data/generate_pdfs.py), so
confidence is uniformly high and raw_text mirrors that script's layout.
llm/reader.py's fixture mode serves these directly; this is why Milestone 2
never needs a live API key to pass its tests.

Run: ../.venv/bin/python build_fixtures.py   (from llm/fixtures/)
"""

import json
from pathlib import Path

import jsonschema

HERE = Path(__file__).parent
REPO_ROOT = HERE.parent.parent
GROUND_TRUTH = REPO_ROOT / "sample_data" / "ground_truth"
SCHEMA_DIR = REPO_ROOT / "ai_studio" / "schema"

HIGH_CONFIDENCE = 0.97


def sf(value, raw_text, confidence=HIGH_CONFIDENCE):
    return {"value": value, "confidence": confidence, "raw_text": raw_text, "notes": None}


def nf(value, raw_text, confidence=HIGH_CONFIDENCE):
    return {"value": value, "confidence": confidence, "raw_text": raw_text, "notes": None}


def rupees(n) -> str:
    return f"Rs. {n:,}"


def build_payslip() -> dict:
    d = json.loads((GROUND_TRUTH / "payslip_riya_sharma_apr2026.json").read_text())
    return {
        "document_type": "payslip",
        "extraction_version": "1.0",
        "warnings": [],
        "fields": {
            "employer_name": sf(d["employer_name"], f"{d['employer_name']} -- Payslip"),
            "employee_name": sf(d["employee_name"], f"Employee name: {d['employee_name']}"),
            "uan": sf(d["uan"], f"UAN: {d['uan']}"),
            "pay_period": sf(d["pay_period"], f"Pay period: {d['pay_period']}"),
            "monthly_gross_salary": nf(d["monthly_gross_salary"], f"Gross monthly salary: {rupees(d['monthly_gross_salary'])}"),
            "basic_pay": nf(d["basic_pay"], f"Basic pay: {rupees(d['basic_pay'])}"),
            "hra": nf(d["hra"], f"House rent allowance: {rupees(d['hra'])}"),
            "special_allowance": nf(d["special_allowance"], f"Special allowance: {rupees(d['special_allowance'])}"),
            "pf_employee_deduction": nf(d["pf_employee_deduction"], f"Provident fund (employee): {rupees(d['pf_employee_deduction'])}"),
            "professional_tax": nf(d["professional_tax"], f"Professional tax: {rupees(d['professional_tax'])}"),
            "tds_deducted": nf(d["tds_deducted"], f"Income tax (TDS): {rupees(d['tds_deducted'])}"),
            "net_pay": nf(d["net_pay"], f"Net pay credited: {rupees(d['net_pay'])}"),
        },
    }


def build_form16() -> dict:
    d = json.loads((GROUND_TRUTH / "form16_riya_sharma_fy2025-26.json").read_text())
    return {
        "document_type": "form16",
        "extraction_version": "1.0",
        "warnings": [],
        "fields": {
            "employer_name": sf(d["employer_name"], f"Employer: {d['employer_name']}"),
            "employee_name": sf(d["employee_name"], f"Employee name: {d['employee_name']}"),
            "pan": sf(d["pan"], f"PAN: {d['pan']}"),
            "financial_year": sf(d["financial_year"], f"FY {d['financial_year']} / AY {d['assessment_year']}"),
            "gross_salary_annual": nf(d["gross_salary_annual"], f"Gross salary (annual): {rupees(d['gross_salary_annual'])}"),
            "standard_deduction": nf(d["standard_deduction"], f"Standard deduction: {rupees(d['standard_deduction'])}"),
            "deductions_chapter_via_total": nf(
                d["deductions_chapter_via_total"],
                f"Chapter VI-A: Section 80C {rupees(d['deductions_chapter_via_breakdown']['section_80c'])} + "
                f"Section 80D {rupees(d['deductions_chapter_via_breakdown']['section_80d'])}",
                confidence=0.85,
            ),
            "taxable_income": nf(d["taxable_income"], f"Total taxable income: {rupees(d['taxable_income'])}"),
            "tax_regime_opted": sf(d["tax_regime_opted"], f"Tax regime opted with employer: {d['tax_regime_opted'].upper()}"),
            "tax_computed_annual": nf(d["tax_computed_annual"], f"Tax on total income: {rupees(d['tax_computed_annual'])}"),
            "tds_deducted_annual": nf(d["tds_deducted_annual"], f"Total TDS deducted (annual): {rupees(d['tds_deducted_annual'])}"),
        },
    }


def build_bank_statement() -> dict:
    d = json.loads((GROUND_TRUTH / "bank_statement_riya_sharma_q3fy26.json").read_text())
    return {
        "document_type": "bank_statement",
        "extraction_version": "1.0",
        "warnings": [],
        "account": {
            "account_holder_name": sf(d["account_holder_name"], f"Holder: {d['account_holder_name']}"),
            "account_number_last4": sf(d["account_number_last4"], f"XXXXXXXX{d['account_number_last4']}"),
            "statement_period_from": sf(d["statement_period_from"], f"Period: {d['statement_period_from']} to {d['statement_period_to']}"),
            "statement_period_to": sf(d["statement_period_to"], f"Period: {d['statement_period_from']} to {d['statement_period_to']}"),
            "opening_balance": nf(d["opening_balance"], f"Opening balance: {rupees(d['opening_balance'])}"),
            "closing_balance": nf(d["closing_balance"], f"Closing balance: {rupees(d['closing_balance'])}"),
        },
        "transactions": [
            {
                "date": t["date"],
                "description": t["description"],
                "amount": t["amount"],
                "type": t["type"],
                "running_balance": t["running_balance"],
                "confidence": HIGH_CONFIDENCE,
                "raw_text": f"{t['date']}  {t['description']}  {t['amount']:,}  {t['running_balance']:,}",
                "notes": None,
            }
            for t in d["transactions"]
        ],
    }


def build_pf_passbook() -> dict:
    d = json.loads((GROUND_TRUTH / "pf_passbook_riya_sharma.json").read_text())
    return {
        "document_type": "pf_passbook",
        "extraction_version": "1.0",
        "warnings": [],
        "member": {
            "member_name": sf(d["member_name"], f"Member name: {d['member_name']}"),
            "uan": sf(d["uan"], f"UAN: {d['uan']}"),
        },
        "accounts": [
            {
                "employer_name": acc["employer_name"],
                "member_id": acc["member_id"],
                "period_from": acc["period_from"],
                "period_to": acc["period_to"],
                "balance": acc["balance"],
                # Matches sample_data/generate_pdfs.py: only the active
                # account gets a printed "Status" line -- old accounts print
                # none, since a real passbook doesn't print a dormancy verdict.
                "status_as_printed": "Active" if acc["status"] == "active" else None,
                "confidence": HIGH_CONFIDENCE,
                "raw_text": (
                    f"{acc['employer_name']}  Member ID: {acc['member_id']}  "
                    f"Period: {acc['period_from']} to {acc['period_to'] or 'present'}  Balance: {rupees(acc['balance'])}"
                    + ("  Status: ACTIVE" if acc["status"] == "active" else "")
                ),
                "notes": None if acc["status"] == "active" else "No status line printed for this account.",
            }
            for acc in d["accounts"]
        ],
    }


BUILDERS = {
    "payslip_riya_sharma_apr2026.json": build_payslip,
    "form16_riya_sharma_fy2025-26.json": build_form16,
    "bank_statement_riya_sharma_q3fy26.json": build_bank_statement,
    "pf_passbook_riya_sharma.json": build_pf_passbook,
}

SCHEMAS = {
    "payslip_riya_sharma_apr2026.json": "payslip_schema.json",
    "form16_riya_sharma_fy2025-26.json": "form16_schema.json",
    "bank_statement_riya_sharma_q3fy26.json": "bank_statement_schema.json",
    "pf_passbook_riya_sharma.json": "pf_passbook_schema.json",
}


def main() -> None:
    for out_filename, builder in BUILDERS.items():
        fixture = builder()
        schema = json.loads((SCHEMA_DIR / SCHEMAS[out_filename]).read_text())
        jsonschema.validate(fixture, schema)
        (HERE / out_filename).write_text(json.dumps(fixture, indent=2, ensure_ascii=False) + "\n")
        print(f"wrote {out_filename}, valid against {SCHEMAS[out_filename]}")


if __name__ == "__main__":
    main()
